// -----------------------------------------------------------------------------
// Функція Count(char* str)
// Завдання 1: вияснити, чи є число i таке, що s[i-1] == 'n' та s[i+1] == 'o',
// та порахувати загальну кількість таких груп у рядку.
// -----------------------------------------------------------------------------
int Count(char* str)
{
    // Якщо довжина рядка менша за 3 символи, трійка 'n?o' фізично не може існувати
    if (strlen(str) < 3)
        return 0;

    int k = 0; // лічильник знайдених груп

    // Біжимо циклом по рядку, починаючи з i = 1 (другий символ)
    // і поки наступний символ str[i + 1] не є кінцем рядка '\0'
    for (int i = 1; str[i + 1] != '\0'; i++)
    {
        // Перевіряємо умову Варіанта 16:
        // попередній символ (i - 1) — це буква 'n', а наступний (i + 1) — буква 'o'
        if (str[i - 1] == 'n' && str[i + 1] == 'o')
            k++; // збільшуємо лічильник
    }

    return k; // повертаємо знайдену кількість
}

// -----------------------------------------------------------------------------
// Функція Change(char* str)
// Завдання 2: замінити кожну трійку символів s[i-1], s[i], s[i+1],
// де s[i-1] == 'n' та s[i+1] == 'o' парою зірочок "**".
// -----------------------------------------------------------------------------
char* Change(char* str)
{
    size_t len = strlen(str); // поточна довжина рядка

    // Якщо довжина менша 3, жодна трійка не поміститься — повертаємо без змін
    if (len < 3)
        return str;

    // Виділяємо динамічну пам'ять під новий рядок tmp.
    // Заміна 3 символів "n?o" на 2 символи "**" зменшує довжину, тому len + 1 достатньо.
    char* tmp = new char[len + 1];
    char* t = tmp; // рухомий вказівник на поточну позицію в новому рядку tmp

    tmp[0] = '\0'; // ініціалізуємо порожнім рядком

    size_t i = 0; // індекс сканування вихідного рядка

    // Цикл сканування: поки залишається хоча б 3 символи до кінця рядка
    while (i < len && str[i + 2] != '\0')
    {
        // Перевіряємо трійку символів:
        // str[i] — символ s[i-1] (буква 'n')
        // str[i + 1] — символ s[i] (будь-який проміжний символ)
        // str[i + 2] — символ s[i+1] (буква 'o')
        if (str[i] == 'n' && str[i + 2] == 'o')
        {
            strcat(t, "**"); // дописуємо пару зірочок "**"
            t += 2;          // зміщуємо вказівник на 2 символи вперед
            i += 3;          // перестрибуємо опрацьовану трійку символів
        }
        else
        {
            // Якщо трійка не підійшла, копіюємо один символ як є
            *t++ = str[i++];
            *t = '\0';
        }
    }

    // Докопійовуємо символи, що залишилися в кінці рядка
    while (str[i] != '\0')
    {
        *t++ = str[i++];
    }
    *t = '\0'; // ставимо фінальний нуль-термінатор

    // Копіюємо сформований результат назад у вихідний масив str
    strcpy(str, tmp);

    return tmp; // повертаємо вказівник на модифікований рядок
}
